// Площадка одного заказа на асфальте склада (LKWkalk-41e.2): пунктир складской разметки по периметру
// и бирка с номером заказа в левом верхнем углу.
//
// Почему разметка жёлтая своим токеном, а не `--warning`: это не семантика предупреждения, а краска
// на полу — в одном ряду с `--grid` (сетка разреза) и `--truck` (обводка кузова).
//
// Почему бирка красится цветом ЗАКАЗА, а не той же жёлтой: бирка — единственное место, где номер
// заказа написан во дворе, и её цвет связывает загон со своими стопками и с легендой (design-system
// §6: идентичность заказа — цвет + штриховка). Жёлтой остаётся только краска.
//
// Инертная декорация: лежит под стопками и не берёт указатель — жест «потянуть» внутри загона
// принадлежит стопке. Ручка переноса самого загона — бирка (LKWkalk-36f), см. `data-tag-grip` ниже.
//
// Доступность: весь двор объявлен одним `role="img"` с ярлыком на уровне <svg> в WarehouseFloor,
// поэтому текст внутри вспомогательные технологии не читают — здесь ничего не добавляем, чтобы не
// изображать доступность, которой нет.
import { useId, type PointerEvent as ReactPointerEvent } from 'react';
import { TAG_H, type PlacedBay } from './warehouseLayout';

/** Отступ текста от края бирки, мм — с обеих сторон. */
const TAG_PAD = 70;
/** Номинальная ширина бирки, мм — ровно длина европоддона (LKWkalk-1f5). Мера взята у груза, а не
 *  «под строку»: бирка не должна читаться крупнее того, что подписывает. `SO-1042 · ×18` при этом
 *  умещается полным кеглем, длинный номер ужимается — как и раньше. */
const TAG_W = 1200;
/** Полный кегль бирки, мм. */
const TAG_FONT = TAG_H * 0.62;
/** Ниже этого кегля ярлык перестаёт читаться: дальше ужимать бессмысленно, работает обрезка. */
const TAG_FONT_MIN = TAG_H * 0.3;
/** Средняя ширина знака жирного гротеска в долях кегля. Это ОЦЕНКА, а не замер: во дворе ничего не
 *  измеряется в JS (тот же принцип, что и у масштаба 1:1 — геометрия выводится, а не меряется), а
 *  `textLength` растянул бы короткий ярлык на всю плашку вместо того, чтобы ужать длинный. */
const CHAR_EM = 0.62;

/** Кегль, при котором строка `text` помещается в плашку шириной `plateW` с полями TAG_PAD.
 *  Короткий ярлык рисуется полным кеглем; длинный ужимается ровно настолько, чтобы влезть, но не
 *  ниже TAG_FONT_MIN — за этой границей строку подрезает clip. */
function fitFontSize(text: string, plateW: number): number {
  const inner = plateW - 2 * TAG_PAD;
  const fit = inner / Math.max(text.length, 1) / CHAR_EM;
  return Math.floor(Math.max(TAG_FONT_MIN, Math.min(TAG_FONT, fit)));
}

export function WarehouseBay({
  bay,
  series,
  /** Готовый ярлык: номер заказа либо локализованное «без заказа» — резолвит вызывающий. */
  label,
  onTagDown,
  reorderLabel,
}: {
  bay: PlacedBay;
  /** Слот палитры 1..8 — тот же, что у стопок этого заказа. */
  series: number;
  label: string;
  /** Нажатие на бирку — начало переноса загона (41e.6). Отсутствует — бирка инертна, как и вся
   *  разметка: двор без переноса загонов (например, стенды соседних экранов). */
  onTagDown?: (e: ReactPointerEvent) => void;
  /** Доступное имя ручки (`warehouse.bay.reorder`). Резолвит вызывающий — компонент, как и с
   *  `label`, локалей не читает. */
  reorderLabel?: string;
}) {
  // Страховка, а не рабочая ветка: сегодня `BAY_MIN_W` (1600) больше `TAG_W` (1200), поэтому загон
  // уже бирки раскладка выдать не может и `Math.min` не срабатывает. Оставлено на случай, если
  // минимальная ширина загона когда-нибудь опустится ниже — плашка не должна вылезать за разметку.
  const tagW = Math.min(bay.w, TAG_W);
  // Форма из §1 дизайна: `{orderId} · ×{units}`. Собирается одной строкой, потому что от её длины
  // зависит кегль — считать длину по разрозненным JSX-узлам было бы уже не то же самое, что рисуется.
  const text = `${label} · ×${bay.units}`;
  const fontSize = fitFontSize(text, tagW);
  // Обрезка — последний рубеж под патологический ярлык, который не спасает и минимальный кегль.
  // Не замена ужиманию: обрезанный на полузнаке текст — не решение, а его имитация.
  const clipId = `bay-tag-${useId().replace(/:/g, '')}`;
  return (
    <g data-testid="warehouse-bay" data-order={bay.orderId} pointerEvents="none">
      <rect
        data-outline
        x={bay.x}
        y={bay.y}
        width={bay.w}
        height={bay.h}
        fill="none"
        stroke="var(--yard-mark)"
        strokeWidth={2}
        strokeDasharray="10 7"
        vectorEffect="non-scaling-stroke"
      />
      <clipPath id={clipId}>
        <rect x={bay.x} y={bay.y} width={tagW} height={TAG_H} />
      </clipPath>
      {/* Ручка переноса: единственный узел загона, который берёт указатель. Внешняя группа остаётся
          `pointer-events: none`, а этот потомок возвращает себе попадание — в SVG, как и в CSS,
          `auto` у потомка сильнее унаследованного `none`. Периметр и стопки не задеты: внутри
          загона жест принадлежит стопке. */}
      <g
        data-tag-grip
        pointerEvents={onTagDown ? 'auto' : undefined}
        style={onTagDown ? { cursor: 'grab' } : undefined}
        onPointerDown={onTagDown}
        // Двор — один `role="img"`, поэтому у интерактивной ручки должно быть собственное имя,
        // иначе для скринридера её нет (41e.2 §5). Без жеста ни роли, ни имени: неинтерактивная
        // разметка не должна изображать кнопку.
        role={onTagDown ? 'button' : undefined}
        aria-label={onTagDown ? reorderLabel : undefined}
      >
        <rect data-tag x={bay.x} y={bay.y} width={tagW} height={TAG_H} fill={`var(--s${series})`} />
        <text
          x={bay.x + TAG_PAD}
          y={bay.y + TAG_H / 2}
          fill="var(--brand-ink)"
          fontSize={fontSize}
          fontWeight={700}
          dominantBaseline="central"
          clipPath={`url(#${clipId})`}
        >
          {text}
        </text>
      </g>
    </g>
  );
}
